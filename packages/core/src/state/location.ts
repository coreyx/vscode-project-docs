/**
 * Where the engine keeps its state: a per-user application-data folder shared by the extension and
 * the CLI, so either can continue the other's work (design decision 7, REQ-19.0.2). It's never
 * inside either linked folder.
 */
import { homedir } from "node:os";
import * as path from "node:path";

/** Environment variable that overrides the state root; used by tests and for unusual setups. */
export const STATE_DIR_ENV = "PROJECT_DOCS_STATE_DIR";

/** Returns the root of all Project Docs state for this user on this machine. */
export function stateRoot(
  env: NodeJS.ProcessEnv = process.env,
  platform: NodeJS.Platform = process.platform,
  home: string = homedir(),
): string {
  const override = env[STATE_DIR_ENV];
  if (override) return override;
  if (platform === "win32") {
    return path.win32.join(
      env["APPDATA"] ?? path.win32.join(home, "AppData", "Roaming"),
      "project-docs",
    );
  }
  if (platform === "darwin") {
    return path.posix.join(home, "Library", "Application Support", "project-docs");
  }
  return path.posix.join(
    env["XDG_DATA_HOME"] ?? path.posix.join(home, ".local", "share"),
    "project-docs",
  );
}

/** Project ids are generated by Project Docs; this shape keeps them safe as folder names. */
const PROJECT_ID = /^pd_[0-9a-f-]{8,64}$/;

/** Returns the state folder for one linked project. */
export function projectStateDir(projectId: string, root: string = stateRoot()): string {
  if (!PROJECT_ID.test(projectId))
    throw new Error(`Invalid project id: ${JSON.stringify(projectId)}`);
  return path.join(root, "projects", projectId);
}
